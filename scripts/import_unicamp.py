"""Rebuild the partial-exam History archive from COMVEST's official commentaries.

Requires requests, beautifulsoup4, PyMuPDF, Pillow. Run from the repository root.
Only History/interdisciplinary History questions are reproduced, with attribution.
PDF cache is deliberately not published. No answer is generated by a language model.
"""
from __future__ import annotations

import json
import re
import unicodedata
from pathlib import Path
from urllib.parse import urljoin

import fitz
import requests
from bs4 import BeautifulSoup
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / '.cache/question-import/unicamp'
OUTPUT = ROOT / 'data/question-bank/unicamp.json'
IMAGES = ROOT / 'public/question-bank/images'
INDEX = 'https://www.comvest.unicamp.br/vestibulares-anteriores/1a-fase-2a-fase-comentadas/'


def plain(text):
    return ''.join(c for c in unicodedata.normalize('NFD', text) if not unicodedata.combining(c))


def discover():
    response = requests.get(INDEX, timeout=60)
    response.raise_for_status()
    response.encoding = 'utf-8'
    soup = BeautifulSoup(response.text, 'html.parser')
    year = phase = None
    sources = []
    for el in soup.find_all(['h3', 'p', 'a']):
        title = plain(el.get_text(' ', strip=True))
        if el.name in ['h3', 'p']:
            match = re.fullmatch(r'Provas comentadas (20\d\d)', title, re.I)
            if match:
                year, phase = int(match[1]), None
            if title.startswith('1\u00aa Fase'):
                phase = 1
            if title.startswith('2\u00aa Fase'):
                phase = 2
        if el.name != 'a' or not year or not 2017 <= year <= 2026 or '.pdf' not in el.get('href', ''):
            continue
        if ((phase == 1 and any(t in title for t in ['Questoes', 'Conhecimentos Gerais', 'Historia']) and 'Biologicas' not in title)
                or (phase == 2 and (title == 'Historia' or ('Ciencias Humanas' in title and 'Interdisciplinar' not in title)))):
            sources.append(dict(year=year, phase=phase, url=urljoin(INDEX, el['href']), title=title))
    sources.extend([
        dict(year=2021,phase=1,variant='bio',title='Conhecimentos Gerais - Biol\u00f3gicas e Sa\u00fade - Prova Q/Z',url='https://www.comvest.unicamp.br/wp-content/uploads/2022/01/F1_Comentada_Conhec_Gerais_Biologicas_Saude_Q-Z.pdf'),
        dict(year=2020,phase=2,variant='common',title='Interdisciplinares de Ci\u00eancias Humanas - Comum a todos',url='https://www.comvest.unicamp.br/wp-content/uploads/2020/10/prova_comentada_F2_Dia_2_Todos.pdf'),
        dict(year=2021,phase=2,variant='common',title='Interdisciplinares de Ci\u00eancias Humanas - Comum a todos',url='https://www.comvest.unicamp.br/wp-content/uploads/2021/09/F2-Comentada-Inter-Cien-Humanas-Natureza-Matematica.pdf'),
    ])
    CACHE.mkdir(parents=True, exist_ok=True)
    (CACHE / 'sources.json').write_text(json.dumps(sources, ensure_ascii=False, indent=2), encoding='utf8')
    return sources


def lines(page, clip):
    # COMVEST 2017's Word export splits text spans at arbitrary x coordinates.
    # Rejoin spans by their physical baseline rather than PDF object order.
    groups = []
    for block in page.get_text('dict', clip=clip)['blocks']:
        for line in block.get('lines', []):
            if line['dir'][0] < .9:
                continue
            for span in line['spans']:
                text = span['text'].strip()
                if not text:
                    continue
                baseline = span['origin'][1]
                group = next((g for g in groups if abs(g['baseline'] - baseline) < 2), None)
                if group is None:
                    group = {'baseline': baseline, 'spans': [], 'y': span['bbox'][1], 'bottom': span['bbox'][3]}
                    groups.append(group)
                group['spans'].append(span)
                group['y'] = min(group['y'], span['bbox'][1])
                group['bottom'] = max(group['bottom'], span['bbox'][3])
    result = []
    for group in sorted(groups, key=lambda g: g['baseline']):
        text, lastx = '', None
        for span in sorted(group['spans'], key=lambda s: s['bbox'][0]):
            gap = span['bbox'][0] - lastx if lastx is not None else 0
            text += (' ' if text and gap > 1 else '') + span['text']
            lastx = span['bbox'][2]
        group['text'] = re.sub(r'\s+', ' ', text).strip()
        result.append(group)
    return result


def deduplicated_lines(page, clip):
    # 2017's PDF repeats the glyph at each adjacent text-object boundary.
    # Deduplicate only the SAME glyph at the SAME physical origin; legitimate
    # doubled letters elsewhere are untouched.
    groups=[]
    for block in page.get_text('rawdict',clip=clip)['blocks']:
        for line in block.get('lines',[]):
            if line['dir'][0]<.9:
                continue
            for span in line['spans']:
                baseline=span['origin'][1]
                group=next((g for g in groups if abs(g['baseline']-baseline)<2),None)
                if group is None:
                    group={'baseline':baseline,'y':span['bbox'][1],'bottom':span['bbox'][3],'chars':[]}
                    groups.append(group)
                group['y']=min(group['y'],span['bbox'][1])
                group['bottom']=max(group['bottom'],span['bbox'][3])
                for char in span['chars']:
                    if not any(c['c']==char['c'] and abs(c['origin'][0]-char['origin'][0])<1.2 for c in group['chars']):
                        group['chars'].append(char)
    result=[]
    for group in sorted(groups,key=lambda g:g['baseline']):
        chars=sorted(group['chars'],key=lambda c:c['origin'][0])
        text=''.join(c['c'] for c in chars)
        group['text']=re.sub(r'\s+',' ',text).strip()
        if group['text']:
            result.append(group)
    return result


def regions(doc, year, phase):
    result = []
    for page_num, page in enumerate(doc):
        if year == 2022 and not ((phase == 1 and 67 <= page_num+1 <= 77) or (phase == 2 and (2 <= page_num+1 <= 7 or 26 <= page_num+1 <= 35))):
            continue
        top = 100 if year <= 2019 else ((60 if phase==2 else 75) if year == 2022 else (55 if year == 2021 else 35))
        bottom = page.rect.height - (45 if year <= 2019 else 35)
        if phase == 1 and year in [2020, 2023, 2024, 2025, 2026]:
            clips = [fitz.Rect(20, top, page.rect.width / 2 - 2, bottom), fitz.Rect(page.rect.width / 2 + 2, top, page.rect.width - 10, bottom)]
        else:
            clips = [fitz.Rect(20, top, page.rect.width - 10, bottom)]
        for clip in clips:
            content = deduplicated_lines(page, clip) if year==2017 else lines(page, clip)
            if year in [2019, 2022]:
                content.extend(mask_headings(page, year, phase, page_num + 1))
                content.sort(key=lambda line: line['y'])
            result.append(dict(page=page_num, clip=clip, lines=content))
    return result


